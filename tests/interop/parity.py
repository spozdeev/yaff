#!/usr/bin/env python3
"""Measure the real generated checked/trusted APIs against the C++ reader.

Build yaff_generated_interop and the Rust generator in --build-dir, the C++
yaff_interop_bench target in --cpp-build, and Rust bench_parity in Release first.
Inputs are generated by the C++ fixture producer, never supplied externally.
"""
import argparse
import json
import os
from pathlib import Path
import platform
import random
import statistics
import subprocess

ROOT = Path(__file__).resolve().parents[2]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--build-dir", type=Path, default=ROOT / "build/local")
    parser.add_argument("--cpp-build", type=Path, default=ROOT / "build/release")
    parser.add_argument("--rust-binary", type=Path, default=ROOT / "rust/target/release/examples/bench_parity")
    parser.add_argument("--repetitions", type=int, default=5)
    parser.add_argument("--output", type=Path, default=ROOT / "build/parity-results")
    args = parser.parse_args()
    if args.repetitions < 1:
        parser.error("positive repetition count required")
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    for layout in ("flat", "sparse"):
        subprocess.run([str(args.build_dir.resolve() / "tests/interop/yaff_generated_interop"),
                        "write-" + layout, str(output / (layout + ".bin"))], check=True)
    cpp = args.cpp_build.resolve() / "tests/interop/yaff_interop_bench"
    rust = args.rust_binary.resolve()
    rows = []
    for repetition in range(args.repetitions):
        jobs = [(layout, language, binary) for layout in ("flat", "sparse")
                for language, binary in (("cpp", cpp), ("rust", rust))]
        random.Random(7101 + repetition).shuffle(jobs)
        for layout, language, binary in jobs:
            text = subprocess.check_output([str(binary), str(output / (layout + ".bin"))], text=True)
            metrics = {}
            for line in text.splitlines():
                fields = line.split(",")
                metrics[fields[-2]] = float(fields[-1])
            rows.append(dict(repetition=repetition, layout=layout, language=language, metrics=metrics))
        print("Measured repetition", repetition + 1, flush=True)
    result = dict(platform=platform.platform(), machine=platform.machine(),
                  commit=subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip(),
                  dirty=bool(subprocess.check_output(["git", "status", "--porcelain"], cwd=ROOT)),
                  rustc=subprocess.check_output([os.environ.get("RUSTC", "rustc"), "--version"], text=True).strip(),
                  warmup=1000000, samples=7, sample_iterations=5000000, rows=rows)
    (output / "results.json").write_text(json.dumps(result, indent=2) + "\n")
    for layout in ("flat", "sparse"):
        for language in ("cpp", "rust"):
            group = [r["metrics"] for r in rows if r["layout"] == layout and r["language"] == language]
            medians = {key: round(statistics.median(r[key] for r in group), 4) for key in group[0]}
            print(layout, language, json.dumps(medians, sort_keys=True))
    print("Results:", output / "results.json")


if __name__ == "__main__":
    main()
